def generate_sitemap(root, files, site_url, logger, dry_run=False):
    """Generate sitemap.xml from discovered HTML/PHP pages."""
    base = site_url.rstrip("/")
    now = datetime.datetime.now().strftime("%Y-%m-%d")
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    for filepath in files["html"] + files["php"]:
        rel = os.path.relpath(filepath, root).replace(os.sep, "/")
        if rel in ("index.html", "index.php"):
            priority, changefreq = "1.0", "daily"
        elif "product" in rel.lower():
            priority, changefreq = "0.8", "weekly"
        elif "categor" in rel.lower():
            priority, changefreq = "0.7", "weekly"
        else:
            priority, changefreq = "0.5", "monthly"
        lines += [
            "  <url>",
            "    <loc>{}/{}</loc>".format(base, html.escape(rel)),
            "    <lastmod>{}</lastmod>".format(now),
            "    <changefreq>{}</changefreq>".format(changefreq),
            "    <priority>{}</priority>".format(priority),
            "  </url>",
        ]
    lines.append("</urlset>")
    write_file_safe(os.path.join(root, "sitemap.xml"), "\n".join(lines), dry_run)
    logger.log("Generated sitemap.xml ({} URLs)".format(len(files["html"]) + len(files["php"])))


