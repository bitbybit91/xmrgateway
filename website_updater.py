class Logger:
    """Simple logger that writes to console and accumulates entries for a log file."""

    def __init__(self, log_file, dry_run=False):
        self.log_file = log_file
        self.dry_run = dry_run
        self.entries = []

    def log(self, message, level="INFO"):
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        prefix = "[DRY-RUN] " if self.dry_run else ""
        entry = "[{ts}] [{lvl}] {pfx}{msg}".format(
            ts=timestamp, lvl=level, pfx=prefix, msg=message
        )
        self.entries.append(entry)
        print(entry)

    def save(self):
        if not self.dry_run:
            with open(self.log_file, "w", encoding="utf-8") as fh:
                fh.write("\n".join(self.entries))
                fh.write("\n")


