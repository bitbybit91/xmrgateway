def create_backup(website_root, logger, dry_run=False):
    """Create a full backup of the website directory."""
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    parent = os.path.dirname(os.path.abspath(website_root))
    backup_dir = os.path.join(parent, "website_backup_{}".format(timestamp))
    if dry_run:
        logger.log("[DRY-RUN] Would create backup at: {}".format(backup_dir))
        return backup_dir
    logger.log("Creating backup at: {}".format(backup_dir))
    shutil.copytree(website_root, backup_dir)
    logger.log("Backup complete: {}".format(backup_dir))
    return backup_dir


