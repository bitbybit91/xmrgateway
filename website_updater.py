def write_css_and_js(root, logger, dry_run=False):
    for subdir, content, name in (
        ("css", DARK_THEME_CSS, "style.css"),
        ("js", MAIN_JS, "main.js"),
    ):
        dirpath = os.path.join(root, subdir)
        if not dry_run:
            os.makedirs(dirpath, exist_ok=True)
        fpath = os.path.join(dirpath, name)
        logger.log("Writing {}/{}".format(subdir, name))
        write_file_safe(fpath, content, dry_run)


