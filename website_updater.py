def load_config(config_path, logger):
    """Load and merge user config with defaults."""
    config = copy.deepcopy(DEFAULT_CONFIG)
    if os.path.exists(config_path):
        try:
            with open(config_path, "r", encoding="utf-8") as fh:
                user_config = json.load(fh)
            for key, value in user_config.items():
                if isinstance(value, dict) and isinstance(config.get(key), dict):
                    config[key].update(value)
                else:
                    config[key] = value
            logger.log("Loaded config from: {}".format(config_path))
        except (ValueError, IOError) as exc:
            logger.log("Failed to parse config.json: {}".format(exc), "WARNING")
    else:
        logger.log("Config not found at {}, using defaults".format(config_path), "WARNING")

    # Warn if the placeholder wallet address has not been replaced
    wallet = config.get("monero_wallet_address", "")
    if not wallet or wallet.upper().startswith("YOUR_") or "ADDRESS_HERE" in wallet.upper():
        logger.log(
            "monero_wallet_address is still the placeholder value. "
            "Edit config.json with your real XMR address before going live — "
            "otherwise payments will be unrecoverable.",
            "WARNING",
        )

    return config


def load_keywords(keywords_file, logger):
    """Load keywords from a text file (one per line)."""
    keywords = []
    if os.path.exists(keywords_file):
        try:
            with open(keywords_file, "r", encoding="utf-8") as fh:
                keywords = [line.strip() for line in fh if line.strip()]
            logger.log("Loaded {} keywords from {}".format(len(keywords), keywords_file))
        except IOError as exc:
            logger.log("Failed to load keywords: {}".format(exc), "WARNING")
    else:
        logger.log("Keywords file not found: {}".format(keywords_file), "WARNING")
    return keywords


