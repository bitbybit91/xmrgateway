def read_file_safe(filepath):
    """Read a file with encoding fallback."""
    for encoding in ("utf-8", "latin-1", "cp1252"):
        try:
            with open(filepath, "r", encoding=encoding, errors="replace") as fh:
                return fh.read()
        except IOError:
            pass
    return ""


def write_file_safe(filepath, content, dry_run=False):
    """Write content to a file (no-op in dry-run mode)."""
    if dry_run:
        return True
    try:
        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as fh:
            fh.write(content)
        return True
    except IOError:
        return False


