def main():
    ap = argparse.ArgumentParser(
        description="website_updater.py — Modernize static HTML/PHP website files."
    )
    ap.add_argument(
        "--dry-run", action="store_true",
        help="Preview what would change without modifying any files.",
    )
    ap.add_argument(
        "--config", default="config.json",
        help="Path to config.json (default: config.json in current directory).",
    )
    ap.add_argument(
        "--root", default=None,
        help="Path to website root directory (overrides config.json website_root).",
    )
    args = ap.parse_args()
    dry_run = args.dry_run

    if dry_run:
        print("=" * 60)
        print("DRY-RUN MODE — No files will be modified.")
        print("=" * 60)

    # ── Config ──────────────────────────────────────────────────────────────
    config_path = args.config
    if not os.path.isabs(config_path):
        config_path = os.path.join(os.getcwd(), config_path)

    log_path = os.path.join(os.path.dirname(config_path), "update_log.txt")
    logger = Logger(log_path, dry_run=dry_run)

    config = load_config(config_path, logger)

    # Determine website root
    if args.root:
        website_root = os.path.abspath(args.root)
    else:
        raw = config.get("website_root", ".")
        website_root = (
            os.path.abspath(raw)
            if os.path.isabs(raw)
            else os.path.abspath(os.path.join(os.path.dirname(config_path), raw))
        )

    if not os.path.isdir(website_root):
        logger.log("Website root does not exist: {}".format(website_root), "ERROR")
        sys.exit(1)

    logger.log("Website root: {}".format(website_root))

    # ── Keywords ────────────────────────────────────────────────────────────
    kw_file = config.get("keywords_file", "keywords.txt")
    if not os.path.isabs(kw_file):
        kw_file = os.path.join(website_root, kw_file)
    keywords = load_keywords(kw_file, logger)

    # ── Step 1: Backup ───────────────────────────────────────────────────────
    logger.log("─── Step 1: Creating backup ───")
    create_backup(website_root, logger, dry_run)

    # ── Step 2: Directory structure ──────────────────────────────────────────
    logger.log("─── Step 2: Ensuring directory structure ───")
    ensure_directory_structure(website_root, logger, dry_run)

    # ── Step 3: Write CSS & JS ───────────────────────────────────────────────
    logger.log("─── Step 3: Writing CSS & JS assets ───")
    write_css_and_js(website_root, logger, dry_run)

    # ── Step 4: Discover files ───────────────────────────────────────────────
    logger.log("─── Step 4: Discovering files ───")
    files = discover_files(website_root)
    logger.log(
        "Found: {} HTML, {} PHP, {} CSS, {} JS, {} images".format(
            len(files["html"]), len(files["php"]),
            len(files["css"]), len(files["js"]), len(files["images"]),
        )
    )

    # ── Step 5: Check & fix broken links ────────────────────────────────────
    logger.log("─── Step 5: Checking and fixing broken links ───")
    file_index = build_file_index(website_root, files)
    total_fixes = sum(
        check_and_fix_links(fp, website_root, file_index, logger, dry_run)
        for fp in files["html"] + files["php"]
    )
    logger.log("Total broken link fixes: {}".format(total_fixes))

    # ── Step 6: Inject CSS / JS links ───────────────────────────────────────
    logger.log("─── Step 6: Injecting CSS/JS references ───")
    for fp in files["html"] + files["php"]:
        inject_css_link(fp, website_root, logger, dry_run)
        inject_js_link(fp, website_root, logger, dry_run)

    # ── Step 7: SEO meta tags ────────────────────────────────────────────────
    logger.log("─── Step 7: Injecting SEO meta tags ───")
    site_url = config.get("site_url", "http://localhost")
    for fp in files["html"] + files["php"]:
        inject_seo_tags(fp, keywords, site_url, logger, dry_run)

    # ── Step 8: Parse products & categorise ─────────────────────────────────
    logger.log("─── Step 8: Parsing products and categorising ───")

    # Primary: try to extract products from the index page
    products = parse_products_from_index(website_root, logger)

    if products:
        logger.log(
            "Using {} product(s) parsed from index page (primary source)".format(
                len(products)
            )
        )
    else:
        # Fallback: discover individual product files
        logger.log(
            "No index products found; falling back to file-based product discovery"
        )
        products = [
            parse_product(fp)
            for fp in files["html"] + files["php"]
            if is_product_file(fp, website_root)
        ]
        logger.log("Found {} product page(s) via file scan".format(len(products)))

    categories = collections.OrderedDict()
    for product in products:
        cat = product["category"]
        categories.setdefault(cat, []).append(product)

    all_category_names = sorted(categories.keys())
    logger.log(
        "Categories: {}".format(
            ", ".join(all_category_names) if all_category_names else "none"
        )
    )

    # Create individual product pages for index-parsed products that have no file
    for product in products:
        _create_product_page_if_needed(
            product, website_root, all_category_names, config, logger, dry_run
        )

    # ── Step 9: Enhance product pages ───────────────────────────────────────
    logger.log("─── Step 9: Enhancing product pages with pricing controls ───")
    for product in products:
        enhance_product_page(
            product["filepath"], product, website_root,
            all_category_names, config, logger, dry_run,
        )

    # ── Step 10: Category pages ──────────────────────────────────────────────
    logger.log("─── Step 10: Generating category pages ───")
    for category, cat_products in categories.items():
        generate_category_page(
            category, cat_products, website_root,
            all_category_names, config, logger, dry_run,
        )

    # ── Step 11: Index page ──────────────────────────────────────────────────
    logger.log("─── Step 11: Updating index page ───")
    update_index_page(
        website_root, categories, all_category_names, config, logger, dry_run
    )

    # ── Step 12: Payment page ────────────────────────────────────────────────
    logger.log("─── Step 12: Generating payment page ───")
    generate_payment_page(website_root, config, all_category_names, logger, dry_run)

    # ── Step 13: Sitemap & robots ────────────────────────────────────────────
    logger.log("─── Step 13: Generating sitemap.xml and robots.txt ───")
    files_after = discover_files(website_root)
    generate_sitemap(website_root, files_after, site_url, logger, dry_run)
    generate_robots(website_root, site_url, logger, dry_run)

    # ── Done ─────────────────────────────────────────────────────────────────
    logger.log("─── Complete ───")
    if not dry_run:
        logger.save()
        logger.log("Log saved to: {}".format(log_path))

    print("\n\u2713 website_updater.py finished successfully.")
    if dry_run:
        print("  (DRY-RUN mode \u2014 no files were modified)")
    else:
        print("  Log: {}".format(log_path))


if __name__ == "__main__":
    main()
