def inject_css_link(filepath, root, logger, dry_run=False):
    """Ensure the page references css/style.css."""
    content = read_file_safe(filepath)
    if not content or "style.css" in content:
        return False

    rel_css = os.path.relpath(
        os.path.join(root, "css", "style.css"), os.path.dirname(filepath)
    ).replace(os.sep, "/")
    tag = '<link rel="stylesheet" href="{}">'.format(rel_css)

    if "</head>" in content:
        new_content = content.replace("</head>", "  {}\n</head>".format(tag), 1)
    elif re.search(r"<head[^>]*>", content, re.IGNORECASE):
        new_content = re.sub(
            r"(<head[^>]*>)", r"\1\n  " + tag, content, count=1, flags=re.IGNORECASE
        )
    else:
        new_content = tag + "\n" + content

    if new_content != content:
        logger.log("Injected CSS link: {}".format(os.path.relpath(filepath, root)))
        write_file_safe(filepath, new_content, dry_run)
        return True
    return False


def inject_js_link(filepath, root, logger, dry_run=False):
    """Ensure the page references js/main.js."""
    content = read_file_safe(filepath)
    if not content or "main.js" in content:
        return False

    rel_js = os.path.relpath(
        os.path.join(root, "js", "main.js"), os.path.dirname(filepath)
    ).replace(os.sep, "/")
    tag = '<script src="{}"></script>'.format(rel_js)

    if "</body>" in content:
        new_content = content.replace("</body>", "  {}\n</body>".format(tag), 1)
    else:
        new_content = content + "\n" + tag + "\n"

    if new_content != content:
        logger.log("Injected JS link: {}".format(os.path.relpath(filepath, root)))
        write_file_safe(filepath, new_content, dry_run)
        return True
    return False


