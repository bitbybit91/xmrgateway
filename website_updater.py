def _extract_text(html_content):
    """Strip HTML tags and return plain text."""
    content = re.sub(r"<script[^>]*>.*?</script\s*>", "", html_content,
                     flags=re.DOTALL | re.IGNORECASE)
    content = re.sub(r"<style[^>]*>.*?</style\s*>", "", content,
                     flags=re.DOTALL | re.IGNORECASE)
    content = re.sub(r"<[^>]+>", " ", content)
    content = html.unescape(content)
    return re.sub(r"\s+", " ", content).strip()


def _generate_description(text, max_len=160):
    """Generate a short meta description from plain text."""
    if not text:
        return "Privacy-focused online store with secure anonymous payments via Monero."
    desc = ""
    for sentence in re.split(r"[.!?]+", text):
        sentence = sentence.strip()
        if len(sentence) < 10:
            continue
        if len(desc) + len(sentence) + 2 <= max_len:
            desc = (desc + ". " + sentence).strip(". ")
        else:
            break
    if not desc:
        desc = text[:max_len].rsplit(" ", 1)[0]
    return (desc[:max_len] if desc else "Privacy-focused online store.").strip()


def _extract_title(html_content):
    m = re.search(r"<title[^>]*>(.*?)</title>", html_content,
                  re.IGNORECASE | re.DOTALL)
    return html.unescape(m.group(1).strip()) if m else ""


def inject_seo_tags(filepath, keywords, site_url, logger, dry_run=False):
    """Inject / update SEO meta tags in an HTML/PHP file."""
    content = read_file_safe(filepath)
    if not content:
        return False

    text = _extract_text(content)
    title = _extract_title(content) or (
        os.path.splitext(os.path.basename(filepath))[0]
        .replace("-", " ").replace("_", " ").title()
    )
    description = _generate_description(text)
    kw_str = ", ".join(keywords[:25]) if keywords else ""

    # Build replacement block
    tags = []
    tags.append('<meta charset="UTF-8">')
    tags.append('<meta name="viewport" content="width=device-width, initial-scale=1.0">')
    tags.append('<meta name="robots" content="index, follow">')
    if kw_str:
        tags.append('<meta name="keywords" content="{}">'.format(html.escape(kw_str)))
    tags.append('<meta name="description" content="{}">'.format(html.escape(description)))
    tags.append('<meta property="og:title" content="{}">'.format(html.escape(title)))
    tags.append('<meta property="og:description" content="{}">'.format(html.escape(description)))
    tags.append('<meta property="og:type" content="website">')
    meta_block = "\n    ".join(tags)

    new_content = content
    # Remove pre-existing duplicates
    for pattern in (
        r'\s*<meta\s+charset=["\'][^"\']*["\'][^>]*/?>',
        r'\s*<meta\s+name=["\']keywords["\'][^>]*/?>',
        r'\s*<meta\s+name=["\']description["\'][^>]*/?>',
        r'\s*<meta\s+property=["\']og:[^"\']*["\'][^>]*/?>',
        r'\s*<meta\s+name=["\']robots["\'][^>]*/?>',
        r'\s*<meta\s+name=["\']viewport["\'][^>]*/?>',
    ):
        new_content = re.sub(pattern, "", new_content, flags=re.IGNORECASE)

    # Insert after opening <head> tag
    if re.search(r"<head[^>]*>", new_content, re.IGNORECASE):
        new_content = re.sub(
            r"(<head[^>]*>)",
            r"\1\n    " + meta_block,
            new_content, count=1, flags=re.IGNORECASE,
        )
    elif re.search(r"</head>", new_content, re.IGNORECASE):
        new_content = re.sub(
            r"(</head>)",
            "    " + meta_block + r"\n\1",
            new_content, count=1, flags=re.IGNORECASE,
        )
    else:
        new_content = "<head>\n    {}\n</head>\n".format(meta_block) + new_content

    if new_content != content:
        logger.log("Updated SEO meta tags: {}".format(os.path.relpath(filepath)))
        write_file_safe(filepath, new_content, dry_run)
        return True
    return False


