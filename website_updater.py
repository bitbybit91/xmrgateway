class _LinkExtractor(html.parser.HTMLParser):
    """Extracts href/src/action attribute values from HTML."""

    def __init__(self):
        super(_LinkExtractor, self).__init__()
        self.links = []  # list of (attr_name, value, tag)

    def handle_starttag(self, tag, attrs):
        attrs_dict = dict(attrs)
        for attr in ("href", "src", "action"):
            val = attrs_dict.get(attr, "")
            if val:
                self.links.append((attr, val, tag))


def _is_external(href):
    parsed = urlparse(href)
    return bool(parsed.scheme) and parsed.scheme not in ("", "file")


def _resolve_link(base_file, href, root):
    """Resolve a relative href to an absolute filesystem path."""
    if _is_external(href):
        return None
    href_clean = href.split("?")[0].split("#")[0]
    if not href_clean:
        return None
    base_dir = os.path.dirname(base_file)
    if href_clean.startswith("/"):
        return os.path.normpath(os.path.join(root, href_clean.lstrip("/")))
    return os.path.normpath(os.path.join(base_dir, href_clean))


def build_file_index(root, files):
    """Build filename → [full_path, ...] index for quick lookup."""
    index = collections.defaultdict(list)
    for f in files["all"]:
        index[os.path.basename(f).lower()].append(f)
    return index


def check_and_fix_links(filepath, root, file_index, logger, dry_run=False):
    """Check and fix broken internal links. Returns count of fixes."""
    content = read_file_safe(filepath)
    if not content:
        return 0

    parser = _LinkExtractor()
    try:
        parser.feed(content)
    except Exception:
        pass

    fixes = 0
    new_content = content

    for attr, href, _tag in parser.links:
        if _is_external(href):
            continue
        href_clean = href.split("?")[0].split("#")[0]
        if not href_clean or href_clean.startswith("#"):
            continue

        resolved = _resolve_link(filepath, href_clean, root)
        if resolved and os.path.exists(resolved):
            continue  # link is valid

        # Try to find the file elsewhere in the directory tree
        basename = os.path.basename(href_clean).lower()
        candidates = file_index.get(basename, [])

        if candidates:
            best = candidates[0]
            rel_path = os.path.relpath(best, os.path.dirname(filepath)).replace(os.sep, "/")
            logger.log(
                "Fixed broken link in {}: {} -> {}".format(
                    os.path.relpath(filepath, root), href, rel_path
                )
            )
            for q in ('"', "'"):
                old = "{}={}{}{}".format(attr, q, re.escape(href), q)
                new = "{}={}{}{}".format(attr, q, rel_path, q)
                if re.search("{}={}{}{}".format(attr, q, re.escape(href), q), new_content):
                    new_content = re.sub(
                        "{}={}{}{}".format(attr, q, re.escape(href), q),
                        "{}={}{}{}".format(attr, q, rel_path, q),
                        new_content, count=1
                    )
                    fixes += 1
                    break
        else:
            logger.log(
                "Broken link (unresolvable) in {}: {} (file not found anywhere)".format(
                    os.path.relpath(filepath, root), href
                ),
                "WARNING",
            )

    if fixes > 0:
        write_file_safe(filepath, new_content, dry_run)
    return fixes


