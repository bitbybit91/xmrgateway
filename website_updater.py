IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".gif", ".svg", ".webp", ".ico", ".bmp"}


def discover_files(root):
    """Walk the website directory and classify files."""
    result = {"html": [], "php": [], "css": [], "js": [], "images": [], "all": []}
    for dirpath, dirnames, filenames in os.walk(root):
        # Skip backup directories in-place
        dirnames[:] = [
            d for d in dirnames
            if not d.startswith("website_backup_") and d not in {".git"}
        ]
        for filename in filenames:
            filepath = os.path.join(dirpath, filename)
            ext = os.path.splitext(filename)[1].lower()
            result["all"].append(filepath)
            if ext == ".html":
                result["html"].append(filepath)
            elif ext == ".php":
                result["php"].append(filepath)
            elif ext == ".css":
                result["css"].append(filepath)
            elif ext == ".js":
                result["js"].append(filepath)
            elif ext in IMAGE_EXTS:
                result["images"].append(filepath)
    return result


