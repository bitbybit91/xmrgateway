def _read_payment_config(repo_root: pathlib.Path) -> dict:
    """Load investment-platform/payment-config.json, or return built-in defaults."""
    path = repo_root / "investment-platform" / "payment-config.json"
    if path.exists():
        with path.open(encoding="utf-8") as fh:
            cfg = json.load(fh)
        try:
            print(f"  [read]  {path.relative_to(repo_root)}")
        except ValueError:
            print(f"  [read]  {path}")
        return cfg
    print(f"  [warn]  {path} not found — using built-in defaults.", file=sys.stderr)
    return _default_config()


def _read_wallet_from_yaml(repo_root: pathlib.Path) -> str:
    """
    Extract ``primary-address:`` from acceptxmr.yaml using only the stdlib.
    Returns an empty string if the file is absent or the key is not found.
    """
    path = repo_root / "acceptxmr.yaml"
    if not path.exists():
        return ""
    text = path.read_text(encoding="utf-8")
    m = re.search(r"^\s*primary-address:\s*(\S+)", text, re.MULTILINE)
    return m.group(1) if m else ""


