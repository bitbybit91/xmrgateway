def _write(path: pathlib.Path, content: str) -> None:
    """Create parent directories as needed and write UTF-8 text with LF endings."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    try:
        rel = path.relative_to(pathlib.Path.cwd())
    except ValueError:
        rel = path
    print(f"  wrote  {rel}")


def _apply_header(template: str, filename: str) -> str:
    """Replace the %%GENERATED_HEADER%% marker with the real header lines."""
    return template.replace(_HDR, _file_header(filename))


