def _file_header(filename: str) -> str:
    """Return a standardised PHP block-comment header (no surrounding /* */)."""
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines = [
        f" * {filename}",
        f" * Auto-generated by configure_site.py v{_VERSION} on {ts}.",
        " * Re-run configure_site.py to regenerate — manual edits will be overwritten.",
    ]
    return "\n".join(lines)


