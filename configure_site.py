        "// ---------------------------------------------------------------------------",
        "// Display settings",
        "// ---------------------------------------------------------------------------",
        "",
        "// Decimal places shown for XMR amounts.",
        "define('XMR_PRECISION', " + str(precision) + ");",
        "",
