"""
configure_site.py
=================
Single-file Python generator.  Reads the ``investment-platform/`` source files
from this repository and writes a complete, upload-ready PHP website with
**zero JavaScript**.  All interactivity and XMR price conversion are handled
server-side in PHP.

Requirements
------------
    Python 3.7+  (standard library only — no pip packages needed)

Usage
-----
    # From the repository root (most common):
    python configure_site.py

    # Specify a custom output directory and wallet address:
    python configure_site.py --output ./my-site --wallet 4YourMoneroAddressHere

    # If running from outside the repository:
    python configure_site.py --repo-root C:\\path\\to\\repo --output C:\\path\\to\\site

Arguments
---------
    --repo-root  PATH   Repository root directory.  Default: current directory.
    --output     PATH   Output directory (created if absent).
                        Default: ./site-output
    --wallet     ADDR   Monero primary receiving address (starts with "4").
                        If omitted the script attempts to read it from
                        acceptxmr.yaml in the repo root.
    --version           Print the script version and exit.

Generated output layout
-----------------------
    <output>/
    ├── .htaccess              Security headers; deny sensitive file types
    ├── index.php              Tier-selection landing page
    ├── pay.php                Payment-display page (XMR amount + address)
    ├── css/
    │   └── payment.css        Pure CSS — no external fonts or CDN imports
    └── includes/
        ├── .htaccess          Deny all direct HTTP access to this directory
        ├── config.php         Tier data, wallet address, API settings
        └── price.php          Server-side XMR price fetcher with file cache

Post-generation steps
---------------------
    1.  Open includes/config.php and confirm XMR_WALLET_ADDRESS.
    2.  Upload the entire output folder to a PHP 7.4+-enabled web host.
    3.  Grant the web server write access to the includes/ directory
        (required for the price_cache.json file created at runtime).
    4.  Browse to index.php to confirm the site works.
"""

